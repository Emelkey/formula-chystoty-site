export function getService(slug: string) {
  const service = servicePages.find((item) => item.slug === slug);
  if (!service) return undefined;

  return { ...service, ...serviceSeoEnhancements[slug] };
}

export function absoluteUrl(path = "/") {
  return `${siteUrl}${path.startsWith("/") ? path : `/${path}`}`;
}

export function buildMetadata({ title, description, path, image = "/images/hero/professional-floor-cleaning-hero.webp", keywords }: { title: string; description: string; path: string; image?: string; keywords?: string[] }): Metadata {
  const url = absoluteUrl(path);
  return {
    title,
    description,
    keywords,
    robots: {
      index: true,
      follow: true
    },
    alternates: {
      canonical: url,
      languages: {
        "uk-UA": url,
        "x-default": url
      }
    },
    openGraph: {
      title,
      description,
      url,
      siteName: contacts.companyName,
      locale: "uk_UA",
      type: "website",
      images: [
        { url: absoluteUrl(image), width: 1200, height: 800, alt: contacts.companyName },
        { url: absoluteUrl("/brand/logo.png"), width: 1254, height: 1254, alt: contacts.companyName }
      ]
    }
  };
}

